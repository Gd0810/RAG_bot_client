def match_quick_response(user_query: str) -> str | None:
    """
    Normalizes user input and checks if it matches any pre-configured
    casual/common quick response phrases. Returns the formatted response or None.
    """
    if not user_query:
        return None

    # Strip punctuation & lowercase for flexible matching
    raw = user_query.strip().lower()
    cleaned = re.sub(r"[^\w\s]", "", raw).strip()

    template = RESPONSES.get(raw) or RESPONSES.get(cleaned)
    if not template:
        return None

    profile = OrganizationProfile.get_solo()
    profile_name = profile.name if (profile and profile.name) else "Your Organization"

    bot_name = profile_name
    workspace_name = profile_name

    return template.format(bot_name=bot_name, workspace_name=workspace_name)
